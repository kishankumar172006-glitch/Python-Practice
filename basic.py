# DATA TYPE IN PYTHON

my_integer = 10
print('Integer:', my_integer)   # used for whole number, cant use decimals

my_float = 4.50
print('float:', my_float)     # used for number with decimal point

my_string = 'Kishan'
print('String:', my_string)   # sequence of characters enclosed in '' or ""

my_boolean = True
print('boolean:', my_boolean)  # A true or false type 



